function runMigrationCli(env, sourceDir) {
	return new Promise((resolve, reject) => {
		const child = spawn("node", [join(REPO_ROOT, "bin", "migrate-to-oss.mjs")], {
			stdio: ["ignore", "pipe", "pipe"],
			env: { ...process.env, ...env, MERMAID_RENDERER_DATA: sourceDir },
		});
		const stderrChunks = [];
		child.stderr.on("data", (chunk) => stderrChunks.push(chunk.toString("utf-8")));
		child.stdout.on("data", () => { /* discard — we don't need the human summary here */ });
		child.on("error", reject);
		child.on("exit", (code) => {
			if (code === 0) resolve({ stderr: stderrChunks.join("") });
			else reject(new Error(`migrate-to-oss exited with code ${code}; stderr: ${stderrChunks.join("")}`));
		});
	});
}

async function listKeysUnderPrefix(client, prefix) {
	const keys = [];
	let token;
	do {
		/** @type {any} */
		const list = await client.send(new ListObjectsV2Command({
			Bucket: bucket,
			Prefix: prefix,
			ContinuationToken: token,
		}));
		const contents = (list && Array.isArray(list.Contents)) ? list.Contents : [];
		for (const obj of contents) {
			if (obj && typeof obj.Key === "string") keys.push(obj.Key);
		}
		token = list && list.NextContinuationToken ? list.NextContinuationToken : null;
	} while (token);
	return keys;
}

