// tests/integration/cloud-proofs/capture-cloud-proofs.mjs
//
// M002/S03 T03 close-out proof capture. Produces the 4 S03 browser-rendered
// proof artifacts under `tests/integration/cloud-proofs/`:
//   1. curl.txt            — curl-style transcript of GET /health
//   2. health.json         — literal /health JSON body
//   3. view-body.html      — HTML body of /view?id=<id> over the cloud backend
//                            (the deterministic text-version fallback for
//                            view-screenshot.png; the agent uses browser
//                            MCP tools to capture the PNG from view-body.html)
//   4. browser-evidence.md — markdown index of the 3 other artifacts with
//                            field-by-field assertions
//
// Why this script is the only entry point:
//   - The T03 plan asks for a deterministic, single-script regeneration
//     of all 4 artifacts. Same pattern as the S02 T04
//     `migrate-to-oss-proofs/capture-dry-run.mjs` and the S04
//     `real-client-smoke/*-cloud.mjs` shapes.
//   - It is MinIO-gated via `probeForSkip` from tests/helpers/oss-fixture.mjs;
//     when the endpoint is unset or unreachable, the script writes a
//     SKIPPED marker to browser-evidence.md and exits 0 (best-effort
//     regeneration, not a failure). This mirrors the S01 T04 +
//     T02 `describe.skipIf` semantics and keeps `node <script>` exit 0
//     for CI.
//
// Why a 2-entry fixture (not the S02 5-entry demo):
//   - S02's purpose is the 4-of-5 post-sweep invariant. S03's purpose is
//     the HTTP browser path. The migration just needs to put SOMETHING
//     in the bucket so the server has at least one entry to render. 2
//     entries (1 fresh + 1 pinned) is the minimum that exercises the
//     bucket write path with non-trivial state.
//
// Why the script does NOT call browser MCP tools:
//   - The MCP `browser_navigate` + `browser_screenshot` tools require
//     macOS Screen Recording permission and are host-level (not Node
//     imports). The script writes `view-body.html` (the literal HTML
//     body the server returned from /view) as a deterministic fallback;
//     the agent running the script uses browser MCP tools to capture
//     `view-screenshot.png` from the saved file. The README documents
//     this two-step regeneration flow.
//
// Run via:  node tests/integration/cloud-proofs/capture-cloud-proofs.mjs

