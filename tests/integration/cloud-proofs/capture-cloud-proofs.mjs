function getFreePort() {
	return new Promise((resolve, reject) => {
		const srv = netCreateServer();
		srv.unref();
		srv.on("error", reject);
		srv.listen(0, "127.0.0.1", () => {
			const addr = srv.address();
			if (!addr || typeof addr === "string") {
				srv.close();
				reject(new Error("could not get free port"));
				return;
			}
			const { port } = addr;
			srv.close(() => resolve(port));
		});
	});
}

async function waitForHealth(port, timeoutMs = 8000) {
	const deadline = Date.now() + timeoutMs;
	let lastErr;
	while (Date.now() < deadline) {
		try {
			const res = await fetch(`http://127.0.0.1:${port}/health`);
			if (res.status === 200) return res;
			lastErr = new Error(`unexpected status ${res.status}`);
			await res.text();
		} catch (e) {
			lastErr = e;
		}
		await new Promise((r) => setTimeout(r, 50));
	}
	throw new Error(
		`/health did not respond on 127.0.0.1:${port} within ${timeoutMs}ms: ${lastErr?.message || "unknown"}`,
	);
}

// Build a curl-style verbose transcript from a raw http.request GET. The
// request line + request headers use the `>` prefix; the response line +
// response headers use `<`; the body is appended at the end. Mirrors
// `curl -v` output shape so the artifact is greppable for HTTP/1.1
// status + content-type without any tool knowledge.
function curlGet(host, port, path, ua) {
	return new Promise((resolve, reject) => {
		const req = http.request(
			{
				hostname: host,
				port,
				method: "GET",
				path,
				headers: {
					Host: `${host}:${port}`,
					"User-Agent": ua,
					Accept: "*/*",
				},
			},
			(res) => {
				const chunks = [];
				res.on("data", (chunk) => chunks.push(chunk));
				res.on("end", () => {
					const bodyBuf = Buffer.concat(chunks);
					const out = [];
					out.push(`> GET ${path} HTTP/1.1`);
					out.push(`> Host: ${host}:${port}`);
					out.push(`> User-Agent: ${ua}`);
					out.push(`> Accept: */*`);
					out.push(">");
					out.push(`< HTTP/1.1 ${res.statusCode} ${res.statusMessage || ""}`);
					for (const [name, value] of Object.entries(res.headers)) {
						if (Array.isArray(value)) {
							for (const v of value) out.push(`< ${name}: ${v}`);
						} else if (value !== undefined) {
							out.push(`< ${name}: ${value}`);
						}
					}
					out.push("<");
					out.push(bodyBuf.toString("utf-8"));
					resolve({ transcript: out.join("\n"), body: bodyBuf.toString("utf-8") });
				});
				res.on("error", reject);
			},
		);
		req.on("error", reject);
		req.end();
	});
}

// ---------------------------------------------------------------------------
// Helpers — 2-entry LocalFsStorage fixture
// ---------------------------------------------------------------------------

// S03 doesn't need the S02 5-entry demo (4-of-5 post-sweep invariant). A
// minimal 2-entry shape (1 fresh-pinned, 1 fresh-unpinned) is enough to
// exercise the bucket write path with non-trivial state. Mirrors the
// makeLocalFixture pattern in tests/helpers/migrate-fixture.mjs but
// inline so the script is self-contained.
async function make2EntryFixture(root) {
	await mkdir(join(root, "blobs"), { recursive: true });
	const now = Date.now();
	const seed = [
		{ id: "cloud-fresh-0", code: "graph TD\n  A-->B", svg: "<svg>cf0</svg>", sourceLength: 13, title: "Cloud Fresh", pinned: true,  expired: false },
		{ id: "cloud-fresh-1", code: "graph LR\n  X-->Y", svg: "<svg>cf1</svg>", sourceLength: 12, title: "Cloud Side", pinned: false, expired: false },
	];
	for (const e of seed) {
		await writeFile(join(root, "blobs", `${e.id}.svg`), e.svg, "utf-8");
	}
	const storage = new LocalFsStorage(root);
	for (const e of seed) {
		storage.store.set(e.id, {
			code: e.code,
			createdAt: now,
			pinned: e.pinned,
			lastAccessedAt: now,
			sourceLength: e.sourceLength,
			title: e.title,
		});
	}
	await storage.save();
	await storage.load();
	return { storage, ids: seed.map((e) => e.id) };
}

