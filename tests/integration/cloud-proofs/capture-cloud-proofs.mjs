async function main() {
	const startedAtIso = new Date().toISOString();
	const directClient = makeDirectClient();

	// -- Step 1: build the 2-entry fixture in a temp dir and migrate to bucket
	const migrationTmp = await mkdtemp(join(tmpdir(), "mermaid-cloud-mig-"));
	let sourceDataDir;
	try {
		const fixture = await make2EntryFixture(migrationTmp);
		// The migration reads from MERMAID_RENDERER_DATA which is the
		// dir root; LocalFsStorage reads from <root>/store.json +
		// <root>/blobs/. The fixture wrote those into migrationTmp.
		sourceDataDir = migrationTmp;

		await runMigrationCli(envForMigration, sourceDataDir);

		// Verify the 2 entries are now in the bucket. Each entry's
		// objects are <prefix>/blobs/<id>.svg + the prefix/store.json
		// — but the migration also writes <prefix>/<id>.svg via
		// OssStorage.save() pattern? No — OssStorage stores under
		// <prefix>/blobs/<id>.svg (the storage layer's key scheme).
		// We assert on the count of <id>.svg keys >= 2.
		const keys = await listKeysUnderPrefix(directClient, migrationPrefix);
		const svgKeys = keys.filter((k) => k.endsWith(".svg"));
		if (svgKeys.length < 2) {
			throw new Error(
				`expected >= 2 .svg keys under prefix ${migrationPrefix}, got ${svgKeys.length} (all keys: ${keys.join(", ")})`,
			);
		}
	} finally {
		await rm(migrationTmp, { recursive: true, force: true });
	}

	// -- Step 2: spawn the cloud-backed HTTP server
	const port = await getFreePort();
	const dataDir = await mkdtemp(join(tmpdir(), "mermaid-cloud-srv-"));
	const server = spawnServer({
		env: {
			...envForServer,
			MERMAID_RENDERER_DATA: dataDir,
			MERMAID_RENDERER_HTTP: "1",
			MERMAID_RENDERER_PORT: String(port),
			MERMAID_RENDERER_HOST: "127.0.0.1",
		},
	});

	let id;
	let fileLink;
	let healthJson;
	let curlTranscript;
	let viewHtml;
	let renderOk = false;
	try {
		await waitForHealth(port);

		// -- Step 3: capture curl.txt + health.json (raw http.request)
		const curlRes = await curlGet(
			"127.0.0.1",
			port,
			"/health",
			`curl-cloud-proofs/${VERSION}`,
		);
		curlTranscript = curlRes.transcript;
		healthJson = JSON.parse(curlRes.body);

		// -- Step 4: render a fresh diagram through the stdio MCP path
		// so the server writes <dataDir>/blobs/<id>.html + .svg under
		// the serverPrefix, which we can then fetch via /view?id=<id>.
		const initRes = await server.send("initialize", {
			protocolVersion: "2025-06-18",
			capabilities: {},
			clientInfo: { name: "cloud-proofs-capture", version: VERSION },
		});
		if (!initRes || !initRes.serverInfo) {
			throw new Error("initialize returned no serverInfo");
		}

		const callRes = await server.send("tools/call", {
			name: "render_mermaid",
			arguments: { code: "graph TD\n  Cloud[Cloud Backend] --> HTTP[HTTP Browser]\n  HTTP --> Browser", title: "Cloud Proof" },
		});
		if (callRes && callRes.content && callRes.content[0] && callRes.content[0].text) {
			const parsed = JSON.parse(callRes.content[0].text);
			if (typeof parsed.id === "string" && parsed.id.length > 0) {
				id = parsed.id;
				fileLink = parsed.fileLink;
				renderOk = true;
			}
		}

		// -- Step 5: fetch the rendered view from the server (the
		// deterministic text-version of the file:// view). The
		// server's /view?id=<id> route returns the self-contained
		// HTML viewer (R003) — same body the operator would see
		// opening the fileLink in a browser.
		if (renderOk) {
			const viewRes = await fetch(`http://127.0.0.1:${port}/view?id=${id}`);
			if (viewRes.status === 200) {
				viewHtml = await viewRes.text();
			}
		}
	} finally {
		try { await server.close(); } catch { /* best-effort */ }
		// Best-effort cleanup of the server's data dir + the server's
		// bucket prefix. Both are deterministic (rebuildable from the
		// script's env) so leaking them on the bucket side only
		// matters for cost; the local dataDir is a fresh mkdtemp.
		await sweepOssPrefix(directClient, bucket, serverPrefix).catch(() => {});
		await rm(dataDir, { recursive: true, force: true }).catch(() => {});
	}

	// -- Step 6: write the 4 artifacts
	await writeFile(join(PROOFS_DIR, "curl.txt"), curlTranscript + "\n", "utf-8");
	await writeFile(join(PROOFS_DIR, "health.json"), JSON.stringify(healthJson, null, 2) + "\n", "utf-8");

	if (renderOk && typeof viewHtml === "string") {
		await writeFile(join(PROOFS_DIR, "view-body.html"), viewHtml, "utf-8");
	}

	// -- Step 7: build browser-evidence.md with field-by-field assertions
	const assertions = [];
	// health.json assertions
	assertions.push(`- \`health.json.version === "${VERSION}\` → ${healthJson && healthJson.version === VERSION ? "PASS" : "FAIL"} (got: ${JSON.stringify(healthJson && healthJson.version)})`);
	assertions.push(`- \`health.json.data === "${bucket}\` → ${healthJson && healthJson.data === bucket ? "PASS" : "FAIL"} (got: ${JSON.stringify(healthJson && healthJson.data)})`);
	assertions.push(`- \`health.json.counters.sweep_runs >= 0\` → ${healthJson && healthJson.counters && typeof healthJson.counters.sweep_runs === "number" && healthJson.counters.sweep_runs >= 0 ? "PASS" : "FAIL"} (got: ${JSON.stringify(healthJson && healthJson.counters && healthJson.counters.sweep_runs)})`);
	assertions.push(`- \`Array.isArray(health.json.last_errors)\` → ${Array.isArray(healthJson && healthJson.last_errors) ? "PASS" : "FAIL"} (got: ${JSON.stringify(healthJson && healthJson.last_errors)})`);
	assertions.push(`- \`typeof health.json.last_render_ms === "number"\` and \`>= 0\` → ${healthJson && typeof healthJson.last_render_ms === "number" && healthJson.last_render_ms >= 0 ? "PASS" : "FAIL"} (got: ${JSON.stringify(healthJson && healthJson.last_render_ms)})`);

	// curl.txt assertions
	const curlHasHttp200 = /< HTTP\/1\.1 200 /.test(curlTranscript);
	const curlHasJsonType = /< content-type: application\/json/i.test(curlTranscript);
	assertions.push(`- \`curl.txt\` contains \`HTTP/1.1 200 \` → ${curlHasHttp200 ? "PASS" : "FAIL"}`);
	assertions.push(`- \`curl.txt\` contains \`content-type: application/json\` (case-insensitive) → ${curlHasJsonType ? "PASS" : "FAIL"}`);

	// curl body == health.json (byte-equal — proves /health and the curl
	// transcript are wire-equivalent). The transcript has a line containing
	// just `<` as the separator between response headers and body; everything
	// after that line is the response body.
	const curlBodyMatch = curlTranscript.match(/^<\n([\s\S]*)$/m);
	const curlBody = curlBodyMatch ? curlBodyMatch[1].replace(/\n$/, "") : "";
	const healthJsonCompact = JSON.stringify(healthJson);
	const bodiesMatch = curlBody === healthJsonCompact;
	assertions.push(`- \`curl.txt\` body byte-equals \`health.json\` (re-serialized) → ${bodiesMatch ? "PASS" : "FAIL"}`);

	// view body assertions
	const viewIdAppears = typeof viewHtml === "string" && id && viewHtml.includes(id);
	assertions.push(`- \`view-body.html\` contains the rendered cloud \`id\` (R003 self-contained viewer) → ${viewIdAppears ? "PASS" : "FAIL"} (id: ${JSON.stringify(id)})`);

	// bucket verification
	const migrationKeys = await listKeysUnderPrefix(directClient, migrationPrefix);
	const migrationSvgs = migrationKeys.filter((k) => k.endsWith(".svg"));
	assertions.push(`- bucket prefix \`${migrationPrefix}\` contains >= 2 .svg entries from the migration → ${migrationSvgs.length >= 2 ? "PASS" : "FAIL"} (got ${migrationSvgs.length})`);

	// Cleanup the migration prefix so the bucket doesn't accumulate
	// artifacts on each run (the server prefix was already cleaned in
	// the server-spawn finally block).
	await sweepOssPrefix(directClient, bucket, migrationPrefix).catch(() => {});

	const evidence = [
		"# M002/S03 cloud proof artifacts",
		"",
		`Generated by \`tests/integration/cloud-proofs/capture-cloud-proofs.mjs\` at ${startedAtIso}.`,
		"",
		"| Artifact | Source | Purpose |",
		"| --- | --- | --- |",
		"| curl.txt | raw `http.request` GET /health | curl-style verbose transcript (request + response lines + headers + body) |",
		"| health.json | literal `fetch('http://127.0.0.1:<port>/health').json()` body | The v0.3.0 /health surface over the cloud backend (MEM037) |",
		"| view-body.html | literal `fetch('http://127.0.0.1:<port>/view?id=<id>').text()` body | The cloud-rendered R003 self-contained HTML viewer; deterministic text-version fallback for view-screenshot.png |",
		"| view-screenshot.png | (not committed by this script) | The agent uses MCP `browser_navigate` + `browser_screenshot` to capture this from view-body.html |",
		"",
		"## Field-by-field assertions",
		"",
		...assertions,
		"",
		"## Reproduction steps",
		"",
		"1. Start MinIO on 127.0.0.1:9000 (or any S3-compatible endpoint):",
		"   ```",
		"   docker run -d -p 9000:9000 -p 9001:9001 \\",
		"     -e MINIO_ROOT_USER=test -e MINIO_ROOT_PASSWORD=testtest \\",
		"     minio/minio server /data --console-address :9001",
		"   ```",
		"2. Create the bucket: `mc mb local/mermaid` (or the AWS CLI equivalent).",
		"3. Export the 5 MERMAID_OSS_* env vars:",
		"   ```",
		'   export MERMAID_OSS_ENDPOINT=http://127.0.0.1:9000',
		'   export MERMAID_OSS_REGION=us-east-1',
		'   export MERMAID_OSS_ACCESS_KEY_ID=test',
		'   export MERMAID_OSS_SECRET_ACCESS_KEY=testtest',
		'   export MERMAID_OSS_BUCKET=mermaid',
		"   ```",
		"4. Run the capture script:",
		"   ```",
		"   node tests/integration/cloud-proofs/capture-cloud-proofs.mjs",
		"   ```",
		"5. (Optional) Capture view-screenshot.png from view-body.html:",
		"   - The agent (or operator with browser MCP tools) navigates to",
		"     the saved `view-body.html` file via `browser_navigate` and",
		"     saves a screenshot to `view-screenshot.png` via",
		"     `browser_screenshot`.",
		"",
		"## Cloud env used for this run",
		"",
		`- Endpoint: \`${endpoint}\``,
		`- Bucket: \`${bucket}\``,
		`- Region: \`${region}\``,
		`- Migration prefix: \`${migrationPrefix}\``,
		`- Server prefix: \`${serverPrefix}\``,
		`- Rendered id: \`${id || "(no render)"}\``,
		`- Rendered fileLink: \`${fileLink || "(no render)"}\``,
		"",
	].join("\n");

	await writeFile(join(PROOFS_DIR, "browser-evidence.md"), evidence + "\n", "utf-8");

	// -- Step 8: print a short summary so the operator sees what happened
	const summary = {
		startedAt: startedAtIso,
		endpoint,
		bucket,
		region,
		migrationPrefix,
		serverPrefix,
		renderId: id,
		healthFields: healthJson && Object.keys(healthJson).sort(),
		healthVersion: healthJson && healthJson.version,
		healthData: healthJson && healthJson.data,
		healthCounters: healthJson && healthJson.counters,
		healthLastErrorsIsArray: Array.isArray(healthJson && healthJson.last_errors),
		healthLastRenderMs: healthJson && healthJson.last_render_ms,
		curlHasHttp200,
		curlHasJsonType,
		bodiesMatch,
		viewIdAppears,
		migrationSvgCount: migrationSvgs.length,
	};
	process.stdout.write(JSON.stringify(summary, null, 2) + "\n");
}

main().catch((e) => {
	// Best-effort: do NOT fail the run on a transient error mid-capture.
	// The script writes whatever artifacts it produced before the
	// failure and exits 0; the failure is in the stdout summary.
	process.stderr.write(`capture-cloud-proofs: ${e?.stack || e?.message || e}\n`);
	process.exit(1);
});
